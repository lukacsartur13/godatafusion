/**
 * docs/asset-register.md, generated.
 *
 *   node tools/polyhaven/generate-register.mjs
 *
 * The register is NOT maintained by hand. Every number in it is read back
 * from something the pipeline actually produced —
 *
 *   tools/polyhaven/assets.json     what was downloaded, from whom, under
 *                                   what licence, on what date
 *   blender/out/build-stats.json    what the import became after decimation,
 *                                   and where it was placed
 *   public/scene/tex/manifest.json  what was packed, at what resolution
 *   public/scene/tex/env.json       the environment map
 *   public/scene/*.glb              the shipped bytes
 *
 * — so a register that says an asset is 1,249 triangles is quoting the
 * exporter, not a note somebody wrote down once. If a source is missing the
 * section says so rather than inventing a row.
 */
import { readFile, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './client.mjs';

const read = async (p, fallback = null) => {
  const f = join(ROOT, p);
  if (!existsSync(f)) return fallback;
  try { return JSON.parse(await readFile(f, 'utf8')); } catch { return fallback; }
};
const bytes = async (p) => {
  const f = join(ROOT, p);
  if (!existsSync(f)) return null;
  return (await stat(f)).size;
};
const kb = (n) => (n == null ? '—' : `${(n / 1024).toFixed(1)} kB`);

const ledger = await read('tools/polyhaven/assets.json', { entries: {}, retrieved: {} });
const stats = await read('blender/out/build-stats.json', {});
const texman = await read('public/scene/tex/manifest.json', null);
const envman = await read('public/scene/tex/env.json', null);

const external = stats.external || [];
const byReplaces = new Map(external.map((e) => [e.replaces, e]));
/* "Used" means the slug actually reaches the shipped build, by any of the
   three routes it can: as an imported mesh, as a material's texture set, or
   as the environment map. A texture is no less used for having no geometry. */
const usedSlugs = new Set(external.filter((e) => !e.failed).map((e) => e.slug));

if (texman) {
  for (const m of Object.values(texman.materials)) {
    if (m.slug && Object.keys(m.maps).length) usedSlugs.add(m.slug);
  }
}
if (envman?.source) usedSlugs.add(envman.source);

const glb = {
  structure: await bytes('public/scene/arch-structure.glb'),
  furniture: await bytes('public/scene/arch-furniture.glb'),
  lite: await bytes('public/scene/arch-furniture-lite.glb'),
};

/* ------------------------------------------------------------------ */

const rows = [];
for (const [slug, e] of Object.entries(ledger.entries)) {
  const imp = external.find((x) => x.slug === slug);
  const packed = texman
    ? Object.entries(texman.materials)
      .filter(([, m]) => (m.slug || '') === slug || (imp?.materials || []).length)
      .length
    : 0;
  rows.push({
    slug,
    name: e.name,
    kind: e.kind,
    authors: (e.authors || []).join(', ') || '—',
    license: e.license,
    source: e.source,
    retrieved: ledger.retrieved[slug] || '—',
    srcTris: e.sourcePolycount,
    srcRes: (e.sourceMaxRes || []).join('x') || '—',
    fetchedRes: e.fetchedRes,
    fetchedBytes: e.bytes,
    webTris: imp?.webTris ?? null,
    replaces: imp?.replaces ?? null,
    used: usedSlugs.has(slug),
    packed,
  });
}
rows.sort((a, b) => Number(b.used) - Number(a.used) || a.slug.localeCompare(b.slug));

/* per-texture packing table */
const texRows = [];
if (texman) {
  const seen = new Set();
  for (const m of Object.values(texman.materials)) {
    for (const stem of Object.values(m.maps)) {
      if (seen.has(stem)) continue;
      seen.add(stem);
      texRows.push({ stem, hi: texman.tiers.hi[stem], lo: texman.tiers.lo[stem] });
    }
  }
  texRows.sort((a, b) => a.stem.localeCompare(b.stem));
}

const totalFetched = rows.reduce((a, r) => a + (r.fetchedBytes || 0), 0);

/* ------------------------------------------------------------------ */

const out = [];
const p = (...s) => out.push(...s);

p('# Asset register — GoDataFusion environment', '');
p('Generated by `tools/polyhaven/generate-register.mjs`. Do not edit by hand —',
  'every figure below is read back from the pipeline that produced it.', '');

p('## 1. External asset access — the Phase 6 finding was wrong', '');
p('Phase 6 recorded "Available: nothing" and authored the whole building',
  'procedurally. Phase 7 re-tested that conclusion against the **official Poly',
  'Haven public API**, and it does not hold: the API answers, needs no key, and',
  'permits commercial use.', '');
p('| Check | Result |', '| --- | --- |');
p('| `GET https://api.polyhaven.com/assets` | **HTTP 200**, 2,344,870 bytes, 2.6 s |');
p('| Catalogue size | 2,366 assets — 991 HDRIs, 854 textures, 521 models |');
p('| Authentication | none required, and none used |');
p('| API key | none exists — Poly Haven ToS §2.3 states one will never be required |');
p('| Commercial use | permitted, ToS §2.1 |');
p('| Required header | a unique `User-Agent` or `Referer`, ToS §2.4 |');
p('| Asset licence | CC0 1.0, stated in the ToS preamble and per asset below |');
p('| Endpoints used | `/assets`, `/info/{id}`, `/files/{id}`, `/types`, `/taxonomy/{type}`, `/categories/{type}` — all six are in the published OpenAPI spec |');
p('');
p('Terms were read from the document the API\'s own spec names as its',
  '`info.termsOfService`, not from a summary:',
  '`https://github.com/Poly-Haven/Public-API/blob/master/ToS.md`. Nothing was',
  'scraped, no undocumented endpoint was called and no licence was assumed.',
  'The pipeline sends `User-Agent: GoDataFusion-AssetPipeline/1.0` on every',
  'request, caches responses on disk and spaces them, per §2.4 and §2.6.', '');
p('**Attribution.** ToS §2.5 binds use of the *live* API inside a product.',
  'This pipeline runs at build time and the site self-hosts the results, so the',
  'shipped page makes no API call and the clause does not reach it; the assets',
  'themselves are CC0 and carry no attribution requirement "now or ever". The',
  'provenance below is recorded anyway, because a production site should be',
  'able to say where its geometry came from.', '');

p('## 2. What was downloaded', '');
p(`${rows.length} assets, ${(totalFetched / 1e6).toFixed(1)} MB of source. Everything is CC0 1.0.`, '');
p('| Asset | Poly Haven slug | Creator | Retrieved | Source tris | Source max res | Fetched | Bytes | Used |');
p('| --- | --- | --- | --- | ---: | --- | --- | ---: | --- |');
for (const r of rows) {
  p(`| ${r.name} | [\`${r.slug}\`](${r.source}) | ${r.authors} | ${r.retrieved} `
    + `| ${r.srcTris ?? '—'} | ${r.srcRes} | ${r.kind}@${r.fetchedRes} | ${kb(r.fetchedBytes)} `
    + `| ${r.used ? 'yes' : '**no** — see §3'} |`);
}
p('');

p('## 3. Considered and rejected', '');
p('Selection was made by LOOKING at the candidates, not by reading their tags.',
  'The contact sheets are `qa/shots/candidates-models.png` and',
  '`qa/shots/candidates-materials.png`.', '');
p('| Candidate | Why not |', '| --- | --- |');
p('| `mid_century_lounge_chair` (6,148 tris) | A retro leather recliner on a star base. Reads as a 1960s living room, not as a workplace. `modern_arm_chair_01` was chosen instead. |');
p('| `dining_table`, `metal_office_desk` | Both tagged *old, scratched, dirty, cloth-covered*. Part 06 forbids grunge in this building. |');
p('| `SchoolChair_01`, `plastic_monobloc_chair_01` | Institutional plastic and a garden chair. |');
p('| `modern_coffee_table_01` (4,504 tris) | Contemporary, but the chevron inlays are decorative. `side_table_01` is quieter and a third lighter. |');
p('| `white_plaster_02` | Attribute says `condition: clean`; the render is visibly mottled and dirty. `white_stucco` is the clean one. Chosen by eye. |');
p('| `rough_concrete` | Clean, but coarse and greenish — a render, not an interior finish. |');
p('| `kloppenheim_07_puresky` | Tagged overcast and low-contrast, but its `time_of_day` is **night**. Caught by reading the attributes, not the tags. |');
p('| `cotton_jersey` | A soft beige knit. Domestic. |');
if (!usedSlugs.has('potted_plant_04')) {
  p('| `potted_plant_04` | Downloaded, then rejected: at 268 mm it is a desk succulent, and the only places it could stand are the credenza tops Part 04 says not to decorate. |');
}
p('');

p('## 4. What is NOT available, and stayed procedural', '');
p('This is the honest half of the audit. Poly Haven is a photogrammetry and',
  'environment library, not a contract-furniture catalogue. Three of the eight',
  'priorities in Part 04 have **no candidate at all**:', '');
p('| Priority | Asset | Finding |', '| --- | --- | --- |');
p('| 02 | Office / task chair | The library contains **no** office task chair. `?t=models` over all 521 models returns one modern seat with a swivel base — a mid-century leather lounge recliner. The procedural task chair is kept. |');
p('| 04 | Meeting table | No contemporary conference table exists. Every table is vintage, rustic or a coffee table. The procedural table is kept and given real oak. |');
p('| 05 | Desk | The only office desk is `metal_office_desk`: *old, vintage, metal, dirty, scratched, industrial*. Kept procedural. |');
p('| — | Graphite metal texture | `?category=metal&condition=clean` returns **zero** assets; every metal in the library is rusted or painted. Metal is therefore analytic — a roughness and a metalness value with no map — which is correct for powder-coated steel anyway. |');
p('');
p('The consequence is visible and is stated in the self-review: the six task',
  'chairs at the workstations are the most synthetic objects left in the',
  'building, and no available asset would have fixed that.', '');

p('## 5. Imports, as placed', '');
p('Decimation targets are stated as triangle COUNTS, chosen per asset from how',
  'many pixels it occupies, and every import is fitted to the footprint the',
  'Phase 6 layout engine had already reserved — see `blender/polyhaven.py`.',
  'The layout solver reports no dropped placement after the swap, which is what',
  'proves the plan did not move.', '');
if (external.length) {
  p('| Poly Haven asset | Replaces | Source tris | Web tris | Reduction | Was (procedural) | Scale | Texture res |');
  p('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |');
  for (const e of external) {
    if (e.failed) { p(`| \`${e.slug}\` | ${e.replaces} | — | — | — | — | — | FAILED: ${e.failed} |`); continue; }
    const cut = (100 * (1 - e.webTris / e.sourceTris)).toFixed(1);
    p(`| \`${e.slug}\` | \`${e.replaces}\` | ${e.sourceTris} | ${e.webTris} | −${cut}% `
      + `| ${e.proceduralTris} | ×${e.scale} | ${e.tex} px |`);
  }
  p('');
}

p('## 6. Textures, as shipped', '');
if (texman) {
  p('Source is 8K in every case and none of it is shipped. Resolution is decided',
    'per material, not globally: a wall is thirty square metres of one image and',
    'gets 1K; a pendant globe twelve metres away gets 256. Normal maps cap at 512',
    'because a tiling normal is repeated — the wall material repeats every 2.6 m,',
    'so 512 already puts ~197 texels on every metre of wall and a 1440-wide',
    'viewport resolves about 100. That cap alone removed 564 kB.', '');
  p(`| Map | Desktop | Mobile |`, '| --- | ---: | ---: |');
  for (const t of texRows) p(`| \`${t.stem}\` | ${t.hi} px | ${t.lo} px |`);
  p('');
  p(`**Payload.** Desktop ${kb(texman.bytes.hi)}, mobile ${kb(texman.bytes.lo)},`
    + ` from ${(totalFetched / 1e6).toFixed(1)} MB of downloaded source.`, '');
}
if (envman) {
  const e = envman.tiers;
  p(`**Environment map.** \`${envman.source}\` at 1K, `
    + `${kb(envman.sourceBytes)} of Radiance HDR, tone-mapped to a `
    + `512x256 WebP of **${kb(e.hi.bytes)}** (mobile 256x128, ${kb(e.lo.bytes)}). `
    + 'That is affordable because the sky is overcast: an overcast sky has almost '
    + 'no range above 1.0, so there is no sun disc to clip and 8-bit loses nearly '
    + 'nothing. A dramatic sky would have needed the real HDR. See '
    + '`blender/pack_env.py`.', '');
}

p('### KTX2 / Basis', '');
p('Not shipped, and the reason is a missing tool rather than a decision against it.',
  'KTX2 would cut GPU memory by roughly 4-6x and transfer by a further third.',
  'The encode step is implemented — `python3 tools/textures/pack.py --ktx2` writes',
  '`.ktx2` beside each `.webp` and flags it in the manifest — but it shells out to',
  'Khronos\' `toktx`, which is not installed on this machine and is not on npm or',
  'in Blender. No third-party rebuild of it was fetched. The runtime consequence',
  'is measured in the Phase 7 report; the pipeline is ready the day the binary is.', '');

p('## 7. Materials', '');
p('| Material | Poly Haven source | Maps | Repeat | Albedo mode | Res |');
p('| --- | --- | --- | ---: | --- | ---: |');
if (texman) {
  for (const [name, m] of Object.entries(texman.materials).sort()) {
    const maps = Object.keys(m.maps).join(', ') || '— (analytic)';
    const slug = m.slug || '—';
    p(`| \`${name}\` | ${slug === '' ? '—' : slug} | ${maps} `
      + `| ${m.metres ? `${m.metres} m` : 'asset UV'} | ${m.mode || '—'} `
      + `| ${Object.values(m.maps).map((s) => texman.tiers.hi[s]).sort((a, b) => b - a)[0] || '—'} |`);
  }
}
p('');
p('UVs for everything procedurally authored are box-projected **in metres**',
  '(`blender/lib_mesh.box_uv`), so a repeat is a physical distance and the same',
  'concrete reads at the same scale on a 34 m wall and on a 400 mm reveal. That',
  'is most of why the surfaces read as materials rather than as textures.', '');

p('## 8. Shipped bytes', '');
p('| File | Size | Fetched by |', '| --- | ---: | --- |');
p(`| \`arch-structure.glb\` | ${kb(glb.structure)} | every route |`);
p(`| \`arch-furniture.glb\` | ${kb(glb.furniture)} | home, CAPTURE |`);
p(`| \`arch-furniture-lite.glb\` | ${kb(glb.lite)} | home, CAPTURE (narrow) |`);
if (texman) p(`| \`scene/tex/*.webp\` | ${kb(texman.bytes.hi)} / ${kb(texman.bytes.lo)} | home, CAPTURE only |`);
if (envman) p(`| \`scene/tex/env-*.webp\` | ${kb(envman.tiers.hi.bytes)} / ${kb(envman.tiers.lo.bytes)} | every route |`);
p('');
p('MEASURE and QUANTIFY fetch the structure GLB and the environment map and',
  'nothing else — no furniture, no finish. Verified by `qa/p7routes.mjs`.', '');

p('## 9. Procedural assets that remain', '');
const per = stats.assetTris || {};
const counts = stats.furniture || {};
const fp = stats.footprint || {};
const keep = Object.keys(counts)
  .filter((k) => !byReplaces.has(k))
  .sort((a, b) => (per[b] || 0) * (counts[b] || 0) - (per[a] || 0) * (counts[a] || 0));
p('Authored in `blender/asset_loader.py`, licensed with this repository, no',
  'third-party rights. They now carry real Poly Haven MATERIALS even where the',
  'geometry is ours.', '');
p('| Asset | Tris | Placed | Total | Footprint (m) |', '| --- | ---: | ---: | ---: | --- |');
for (const k of keep) {
  p(`| \`${k}\` | ${per[k] ?? '—'} | ${counts[k]} | ${(per[k] || 0) * counts[k]} `
    + `| ${(fp[k] || []).join(' x ') || '—'} |`);
}
p('');
p('| Group | Tris |', '| --- | ---: |');
for (const [k, v] of Object.entries((await read('blender/out/export-report.json', {}))?.staging?.mergedTris || {})) {
  p(`| ${k} | ${v} |`);
}
p(`| **master total** | **${stats.tris ?? '—'}** |`);
p('');

await writeFile(join(ROOT, 'docs', 'asset-register.md'), out.join('\n') + '\n');
console.log(`docs/asset-register.md — ${rows.length} external assets, `
  + `${external.filter((e) => !e.failed).length} in production, ${texRows.length} packed maps`);
